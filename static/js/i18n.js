let currentLang = "vi";
let currentTheme = "dark";
const langListeners = [];

export function onLanguageChange(fn) {
  if (typeof fn === "function") langListeners.push(fn);
}

export function t(key) {
  const dict = DICTIONARY[currentLang] || DICTIONARY.vi;
  return dict[key] || DICTIONARY.vi[key] || key;
}

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (!DICTIONARY[lang]) return;
  currentLang = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (_) {}

  document.documentElement.lang = lang;

  // Update all elements with data-i18n
  const elements = document.querySelectorAll("[data-i18n]");
  for (const node of elements) {
    const key = node.dataset.i18n;
    if (key) {
      const translated = t(key);
      if (node.textContent !== translated) {
        node.textContent = translated;
      }
    }
  }

  // Update language toggle buttons
  const langBtns = document.querySelectorAll(".lang-btn");
  for (const btn of langBtns) {
    const on = btn.dataset.lang === lang;
    btn.setAttribute("aria-selected", on ? "true" : "false");
    btn.classList.toggle("active", on);
  }

  // Notify listeners
  for (const fn of langListeners) {
    try {
      fn(currentLang);
    } catch (_) {}
  }
}

export function getTheme() {
  return currentTheme;
}

export function setTheme(theme) {
  currentTheme = theme === "light" ? "light" : "dark";
  try {
    localStorage.setItem(THEME_KEY, currentTheme);
  } catch (_) {}

  document.documentElement.dataset.theme = currentTheme;

  const btn = $("theme-toggle-btn");
  if (btn) {
    const isDark = currentTheme === "dark";
    setText("theme-toggle-icon", isDark ? "🌙" : "☀️");
    setText("theme-toggle-text", isDark ? t("theme_dark") : t("theme_light"));
  }

  updateChartsTheme(currentTheme);
}

export function toggleTheme() {
  setTheme(currentTheme === "dark" ? "light" : "dark");
}

export function initI18nAndTheme() {
  let savedLang = "vi";
  let savedTheme = "dark";
  try {
    savedLang = localStorage.getItem(LANG_KEY) || "vi";
    savedTheme = localStorage.getItem(THEME_KEY) || "dark";
  } catch (_) {}

  setLanguage(DICTIONARY[savedLang] ? savedLang : "vi");
  setTheme(savedTheme);

  const themeBtn = $("theme-toggle-btn");
  if (themeBtn) {
    themeBtn.addEventListener("click", toggleTheme);
  }

  const langBtns = document.querySelectorAll(".lang-btn");
  for (const btn of langBtns) {
    btn.addEventListener("click", () => {
      if (btn.dataset.lang) {
        setLanguage(btn.dataset.lang);
      }
    });
  }
}
